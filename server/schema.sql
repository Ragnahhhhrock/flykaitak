CREATE TABLE IF NOT EXISTS scores (
  id    TEXT PRIMARY KEY,
  name  TEXT NOT NULL,
  score INTEGER NOT NULL,
  grade TEXT,
  ac    TEXT,
  wx    TEXT,
  tod   TEXT,
  ts    INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS scores_rank ON scores (score DESC, ts ASC);

-- Anonymous gameplay events for the public /stats/ dashboard. No IP, no user id.
CREATE TABLE IF NOT EXISTS events (
  id    INTEGER PRIMARY KEY AUTOINCREMENT,
  ts    INTEGER NOT NULL,
  k     TEXT NOT NULL,
  mode  TEXT,
  ac    TEXT,
  wx    TEXT,
  tod   TEXT,
  cause TEXT,
  grade TEXT,
  score INTEGER,
  fpm   INTEGER,
  secs  INTEGER,
  ap    INTEGER
);
CREATE INDEX IF NOT EXISTS events_k_ts ON events (k, ts);

-- Replay share links: one row per uploaded replay video (the files are in the R2 bucket bound as REPLAYS).
-- who is a salted hash of the uploader's address, kept only to limit uploads per hour.
CREATE TABLE IF NOT EXISTS replays (
  id      TEXT PRIMARY KEY,
  ts      INTEGER NOT NULL,
  who     TEXT,
  kind    TEXT,
  grade   TEXT,
  score   INTEGER,
  title   TEXT,
  eyebrow TEXT,
  ac      TEXT,
  route   TEXT,
  w       INTEGER,
  h       INTEGER,
  secs    INTEGER,
  lang    TEXT,
  size    INTEGER,
  poster  INTEGER,
  card    INTEGER
);
CREATE INDEX IF NOT EXISTS replays_who_ts ON replays (who, ts);

-- Paid aircraft (see docs/concorde.md). A licence is a random key; src is 'purchase' (ref = Stripe Checkout session) or 'code' (ref = giveaway code).
CREATE TABLE IF NOT EXISTS licences (
  key     TEXT PRIMARY KEY,
  product TEXT NOT NULL,
  src     TEXT NOT NULL,
  ref     TEXT,
  ts      INTEGER NOT NULL,
  revoked INTEGER NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX IF NOT EXISTS licences_purchase ON licences (ref) WHERE src = 'purchase';
-- Free giveaway codes: max_uses people can each redeem one.
CREATE TABLE IF NOT EXISTS codes (
  code     TEXT PRIMARY KEY,
  product  TEXT NOT NULL,
  max_uses INTEGER NOT NULL DEFAULT 1,
  uses     INTEGER NOT NULL DEFAULT 0,
  note     TEXT,
  ts       INTEGER NOT NULL,
  expires  INTEGER,
  disabled INTEGER NOT NULL DEFAULT 0
);
-- Wrong codes, keys and sessions, to limit guessing. who is a salted hash of the address.
CREATE TABLE IF NOT EXISTS lic_fail (
  who TEXT NOT NULL,
  ts  INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS lic_fail_who_ts ON lic_fail (who, ts);
-- New radio lines generated by the voice service, to limit how many one visitor can ask for. who is a salted hash of the address.
CREATE TABLE IF NOT EXISTS tts_gen (
  who TEXT NOT NULL,
  ts  INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS tts_gen_who_ts ON tts_gen (who, ts);
